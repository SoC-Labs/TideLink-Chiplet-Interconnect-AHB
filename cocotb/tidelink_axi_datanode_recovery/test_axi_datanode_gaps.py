"""AXI data-node COVERAGE-GAP suite — the tests the B-node work never wrote.

Companion to `test_axi_datanode_recovery.py` (Fix G / Fix H / I5). That suite
proves the WRITE-RESPONSE (B) node end to end. This one closes the two holes a
2026-08-02 verification review of the eth-chiplet silicon pushback found in it:

  GAP-1  FOUR OF THE FIVE AXI FC NODES HAVE NO ERROR-INJECTION TEST AT ALL.
         Every existing test injects on data_id 0x82 (B). AW (0x80), W (0x81),
         AR (0x83) and R (0x84) are untested in sim AND on silicon, yet the
         consumer's stated acceptance gate is "errinject per node in
         {AW,W,B,AR,R} x several bits, expect recovery on every one"
         (nanosoc-ethernet-chiplet docs/HANDOVER_AXI_DATANODE_RECOVERY.md).
         The READ path matters most: one of the two originally-reported silicon
         wedge points was a peer READ, and the read return path (AR out, R back)
         has a DIFFERENT backstop than writes — `sub_rd_os_r` is a single BIT,
         not the saturating counter Fix H gave writes.

  GAP-2  THE I5 BACKSTOP'S OWN SEMANTICS ARE UNVERIFIED. I5 is only ever
         observed doing the thing it was built for (fire once, on one stuck
         write, on an otherwise idle link). Four properties it must also hold
         are asserted here for the first time:
           a) the AHB ERROR it emits is a LEGAL AHB-Lite response — i.e. it
              lands in the data phase of a transfer the master is actually
              waiting on, not on an idle bus. I5 is deliberately
              HREADYOUT-BLIND and tracks POSTED (bufferable, HPROT[2]=1)
              writes the master has already retired, so "ERROR into an idle
              bus" is reachable BY CONSTRUCTION -- and an upstream bridge is
              entitled to ignore such a pulse. That is a candidate mechanism
              for the on-silicon "HRESP=ERROR is driven but never reaches the
              PS" (docs/ila_capA_i5_fires_2026_08_02.csv).
           b) a stuck response is still timed out while OTHER traffic is
              progressing. `sub_axi_progress = sub_r_done | sub_b_done` resets
              the ONE shared age counter for ALL outstanding transactions, so
              any completing beat on either channel re-arms the timer for a
              transaction that is genuinely stuck. The on-silicon repro that
              wedged used a 32-beat resume STREAM; the only case ever proven
              in sim or on the ILA is `--stream 0` (a single beat, nothing else
              in flight).
           c) the backstop RESTORES the path. Firing an AHB ERROR upstream does
              not by itself unwedge XHB500: the ILA shows `xhb_sub_hreadyout_raw`
              still 0 and `sub_ext_stalled` re-arming immediately after the
              ERROR (samples 258+). If the window path is dead after one lost
              response, "bounded to HRESP=ERROR" is not the same as "recovered".
           d) it RE-ARMS. On expiry the RTL zeroes `sub_wr_os_ctr`/`sub_rd_os_r`
              to abandon the timed-out transaction, but the abandoned response
              may still arrive later and decrement/clear the tracking of a
              LATER transaction, leaving a second lost response untimed.

Runtime notes (inherited from the companion suite):
  * every test needs its OWN sim — a left-armed Force corrupts the next bring-up
  * built against the SHORT I5 timeout (2^13) so the backstop tests finish;
    `make gaps_*` targets pass +define+TIDELINK_SUB_OUTSTANDING_TIMEOUT_LOG2=13
  * the node-coverage tests (GAP-1) do NOT need the short timeout.
"""
import os
import cocotb
from cocotb.triggers import RisingEdge, ClockCycles
from cocotb.handle import Force, Release

from pair_v2_common import PairV2TB, run_bringup_full

# ── the five AXI FC nodes ────────────────────────────────────────────────────
# data_id: WlinkGenericFCSM{,_1,_2,_3,_4}.v swi_data_id_1 reset defaults.
# tx_side: which die TRANSMITS that packet type for a die-m-initiated access
#          (m issues AW/W/AR; s returns B/R). Inject on the transmitter.
# The NACK is generated by the RECEIVER, i.e. the other die's same-named node.
NODES = {
    "AW": dict(data_id=0x80, inst="wlink_axiawFC", tx_side="m", op="write"),
    "W":  dict(data_id=0x81, inst="wlink_axiwFC",  tx_side="m", op="write"),
    "B":  dict(data_id=0x82, inst="wlink_axibFC",  tx_side="s", op="write"),
    "AR": dict(data_id=0x83, inst="wlink_axiarFC", tx_side="m", op="read"),
    "R":  dict(data_id=0x84, inst="wlink_axirFC",  tx_side="s", op="read"),
}
AXI_FC_NODES = [n["inst"] for n in NODES.values()]

APER_BASE  = 0x4000_0000
OFF_SANITY = 0x100
OFF_INJECT = 0x200
OFF_RD     = 0x300
OFF_POST   = 0x400
D_SANITY   = 0xC0FFEE01
D_INJECT   = 0xBEEF1234
D_RD       = 0x5EED0042
D_POST     = 0xA5A50FF0
REG_OBS_AXI_NODES = 0x21E0

BYTE_PKTNUM = 4    # header pktnum -> isNotExpPacket (detected with CRC on OR off)
# Byte 0 is the packet's `data_id`. The CRC comparison is GATED on
# `data_id === swi_data_id` (FC.scala:157, documented in
# cocotb/tidelink_error_injection/test_ei_crc_probe.py:34-40), so corrupting it
# makes the packet not-a-data-packet: it is silently DROPPED at the receiver, no
# CRC error is raised, no NACK is sent, and nothing is ever replayed. This is
# the "clean silent drop" the on-silicon ILA capture used
# (docs/AXI_DATANODE_RECOVERY_AMPLIFIER_SOUND_2026_08_01.md:232, byte 0 +
# --stream 0) — the failure mode Fix G's NACK/replay is structurally blind to.
BYTE_DATA_ID = 0


# ── hierarchy / force helpers (kept local: importing a module that defines
#    @cocotb.test() risks pulling its tests into this regression) ────────────
def _axi_node(tb, side, inst):
    return getattr(tb.top(side).u_chiplet_controller.u_wlink.axi2wl, inst)


def _wlink(tb, side):
    return tb.top(side).u_chiplet_controller.u_wlink


def _sig(node, name):
    try:    return int(getattr(node, name).value)
    except Exception: return None


def _slave_bram_peek(dut, off):
    try:    return int(dut.u_s_mng_bram.mem[off >> 2].value)
    except Exception: return None


def _force_axi_crc(tb, on):
    for side in ("m", "s"):
        for inst in AXI_FC_NODES:
            try:    _axi_node(tb, side, inst).out_prepend_swi_disable_crc.value = \
                        (Force(0) if on else Release())
            except Exception: pass


def _force_fix_off(tb, off):
    """Force socl_l7_reached_link_data=0 on every AXI node = the PRE-Fix-G RTL
    (bring-up forgive stays armed forever, so a detected error never NACKs)."""
    n = 0
    for side in ("m", "s"):
        for inst in AXI_FC_NODES:
            try:
                _axi_node(tb, side, inst).socl_l7_reached_link_data.value = \
                    (Force(0) if off else Release())
                n += 1
            except Exception: pass
    return n


async def _arm_injector(tb, side, data_id, byte, bit=0):
    """One-shot Wlink built-in injector (the 0x2E03_003C silicon model)."""
    wl = _wlink(tb, side)
    wl.swi_err_inj_data_id.value = Force(data_id)
    wl.out_prepend_swi_err_inj_byte.value = Force(byte)
    wl.out_prepend_swi_err_inj_bit.value = Force(bit)
    wl.out_prepend_swi_err_inj.value = Force(0)
    await ClockCycles(tb.dut.hclk, 4)
    wl.out_prepend_swi_err_inj.value = Force(1)
    await ClockCycles(tb.dut.hclk, 4)


async def _arm_injector_persistent(tb, side, data_id, byte, bit=0):
    """PERSISTENT injection: hold err_inj_smack high so every matching SOP —
    including every NACK-driven REPLAY — is re-corrupted, i.e. the response can
    never converge. Models a permanently-lost response."""
    wl = _wlink(tb, side)
    wl.swi_err_inj_data_id.value = Force(data_id)
    wl.out_prepend_swi_err_inj_byte.value = Force(byte)
    wl.out_prepend_swi_err_inj_bit.value = Force(bit)
    wl.lltx.err_inj_smack.value = Force(1)
    await ClockCycles(tb.dut.hclk, 4)


def _disarm_injector(tb, side):
    wl = _wlink(tb, side)
    for a in ("swi_err_inj_data_id", "out_prepend_swi_err_inj_byte",
              "out_prepend_swi_err_inj_bit", "out_prepend_swi_err_inj"):
        try:    getattr(wl, a).value = Release()
        except Exception: pass
    try:    wl.lltx.err_inj_smack.value = Release()
    except Exception: pass


def _release_all(tb):
    for side in ("m", "s"):
        _disarm_injector(tb, side)
        for inst in AXI_FC_NODES:
            node = _axi_node(tb, side, inst)
            for a in ("out_prepend_swi_disable_crc", "socl_l7_reached_link_data"):
                try:    getattr(node, a).value = Release()
                except Exception: pass


async def _region_f(tb):
    try:    raw = await tb.apb("m").read(REG_OBS_AXI_NODES)
    except Exception: return (None, None, None)
    return ((raw >> 23) & 1, ((raw >> 12) & 1) | ((raw >> 17) & 1), raw)


# ── AHB-Lite master on m_ahb_sub_* ───────────────────────────────────────────
class AHBSubMaster:
    """Single-beat AHB-Lite master. TimeoutError = response never returned;
    RuntimeError = HRESP=ERROR (a backstop fired); clean return = completed.

    Adds, over the companion suite's copy, an `activity` trace: for every clock
    it records whether the master had a transfer OUTSTANDING (address accepted,
    data phase not yet complete). `test_i5_error_is_ahb_legal` uses it to decide
    whether an ERROR pulse landed on a real transfer or on an idle bus."""

    def __init__(self, dut):
        self.dut = dut; self.clk = dut.hclk
        self.hsel = dut.m_ahb_sub_hsel; self.haddr = dut.m_ahb_sub_haddr
        self.hburst = dut.m_ahb_sub_hburst; self.hprot = dut.m_ahb_sub_hprot
        self.hsize = dut.m_ahb_sub_hsize; self.htrans = dut.m_ahb_sub_htrans
        self.hwdata = dut.m_ahb_sub_hwdata; self.hwrite = dut.m_ahb_sub_hwrite
        self.hready = dut.m_ahb_sub_hready; self.hrdata = dut.m_ahb_sub_hrdata
        self.hresp = dut.m_ahb_sub_hresp; self.hreadyout = dut.m_ahb_sub_hreadyout
        self.outstanding = False       # a transfer is in its data phase
        self.idle()

    def idle(self):
        self.hsel.value = 0; self.haddr.value = 0; self.hburst.value = 0
        self.hprot.value = 0; self.hsize.value = 2; self.htrans.value = 0
        self.hwdata.value = 0; self.hwrite.value = 0; self.hready.value = 1
        self.outstanding = False

    def _resp(self):
        try:    return int(self.hresp.value)
        except ValueError: return 0

    def _rdata(self):
        try:    return int(self.hrdata.value)
        except ValueError: return -1

    async def _run(self, addr, write, wdata, timeout):
        await RisingEdge(self.clk)
        self.hsel.value = 1; self.haddr.value = addr & 0xFFFF_FFFF
        self.htrans.value = 2; self.hsize.value = 2; self.hburst.value = 0
        self.hprot.value = 0; self.hwrite.value = 1 if write else 0
        self.hready.value = 1
        if write: self.hwdata.value = wdata & 0xFFFF_FFFF
        await RisingEdge(self.clk)
        self.hsel.value = 0; self.htrans.value = 0; self.hwrite.value = 0
        self.hburst.value = 0
        self.outstanding = True
        seen_low = False; rdata, resp, done = -1, 0, False
        for _ in range(timeout):
            await RisingEdge(self.clk)
            r = int(self.hreadyout.value)
            if not r: seen_low = True
            elif seen_low:
                rdata = self._rdata(); resp = self._resp(); done = True; break
        self.idle()
        op = "WRITE" if write else "READ"
        if not done: raise TimeoutError(f"ahb_sub {op} 0x{addr:08x} WEDGE")
        if resp:     raise RuntimeError(f"ahb_sub {op} 0x{addr:08x} HRESP=ERROR")
        return rdata

    async def write(self, addr, data, timeout=80000):
        await self._run(addr, True, data, timeout)

    async def read(self, addr, timeout=80000):
        return await self._run(addr, False, 0, timeout)

    async def write_bufferable(self, addr, data, node, timeout=80000):
        """Bufferable single write (HPROT[2]=1 -> XHB500 early-write-response).
        The master is RELEASED as soon as the bridge posts it, so after this
        returns the AHB bus is IDLE while the write is still outstanding on
        s_axi. Completion is detected by this write's AW being accepted.
        `node` is the tidelink_top instance (dut.u_master), which is where the
        XHB500 s_axi handshakes are visible."""
        await RisingEdge(self.clk)
        self.hsel.value = 1; self.haddr.value = addr & 0xFFFF_FFFF
        self.htrans.value = 2; self.hsize.value = 2; self.hburst.value = 0
        self.hprot.value = 0x4; self.hwrite.value = 1; self.hready.value = 1
        self.hwdata.value = data & 0xFFFF_FFFF
        await RisingEdge(self.clk)
        self.hsel.value = 0; self.htrans.value = 0; self.hwrite.value = 0
        self.outstanding = True
        accepted = False
        for _ in range(timeout):
            await RisingEdge(self.clk)
            try:
                if int(node.s_axi_awvalid.value) and int(node.s_axi_awready.value):
                    accepted = True; break
            except ValueError: pass
            if int(self.hreadyout.value) and self._resp():
                self.idle(); raise RuntimeError(f"ahb_sub bufW 0x{addr:08x} HRESP=ERROR")
        if accepted:
            await ClockCycles(self.clk, 4)
        self.idle()
        if not accepted: raise TimeoutError(f"ahb_sub bufW 0x{addr:08x} STALL")
        return True


async def _err_watch(dut, master, out, cycles):
    """Sample the master-facing AHB response every cycle. Records each HRESP=1
    pulse together with whether the master had a transfer outstanding at the
    time — the AHB-Lite legality question. Also tracks the DUT-internal
    backstop registers so 'no ERROR at all' can be told apart from 'ERROR fired
    but invisible at the port'."""
    prev = 0
    out.setdefault("pulses", [])
    out.setdefault("err1_fires", 0)
    out.setdefault("osr_max", 0)
    prev_e1 = 0
    for _ in range(cycles):
        await RisingEdge(dut.hclk)
        try:
            e1 = int(dut.u_master.sub_err1_r.value)
            if e1 and not prev_e1: out["err1_fires"] += 1
            prev_e1 = e1
            c = int(dut.u_master.sub_osr_ctr_r.value)
            if c > out["osr_max"]: out["osr_max"] = c
        except Exception: pass
        try:    resp = int(dut.m_ahb_sub_hresp.value)
        except ValueError: continue
        if resp and not prev:
            out["pulses"].append({
                "outstanding": master.outstanding,
                "hreadyout": int(dut.m_ahb_sub_hreadyout.value),
            })
        prev = resp


