@cocotb.test()
async def test_i5_error_is_ahb_legal(dut):
    """GAP-2a — the ERROR I5 emits must be a LEGAL AHB-Lite response.

    Scenario: a POSTED (bufferable) write whose B is permanently corrupted.
    XHB500's early-write-response releases the AHB master immediately, so the
    bus is IDLE while the write is still outstanding on s_axi — exactly the
    case I5 exists for (the per-beat stall timer is blind to it because
    HREADYOUT is high). When I5 expires it drives HRESP=1 for two cycles.

    AHB-Lite: a subordinate may only signal ERROR during the DATA PHASE of a
    transfer it was selected for. If HRESP=1 is asserted with no transfer
    outstanding, an upstream bridge is entitled to discard it — which would
    explain the silicon observation that I5 drove HRESP=ERROR and the PS never
    saw a bus error (docs/ila_capA_i5_fires_2026_08_02.csv).

    FAIL here = a real defect: `ahb_sub_hresp`/`ahb_sub_hreadyout` are driven
    from `sub_err{1,2}_r` alone (tidelink_top.sv ~:1703-1710), with NO
    qualification that a transfer is in its data phase."""
    tb, master = await _bringup(dut)
    trace = {}
    w = cocotb.start_soon(_err_watch(dut, master, trace, 60000))

    await _arm_injector_persistent(tb, "s", NODES["B"]["data_id"], BYTE_PKTNUM)
    try:
        await master.write_bufferable(APER_BASE + OFF_POST, D_POST,
                                      dut.u_master, timeout=20000)
    except (TimeoutError, RuntimeError) as e:
        dut._log.info(f"[gaps] posted write did not post cleanly: {e}")

    # Master is now idle; wait past the (short-build) I5 timeout.
    await ClockCycles(dut.hclk, 40000)
    w.kill()
    _release_all(tb)
    dut._log.info(f"[gaps] err1_fires={trace['err1_fires']} osr_max={trace['osr_max']} "
                  f"HRESP pulses={trace['pulses']}")

    assert trace["err1_fires"] > 0, (
        f"NO BACKSTOP AT ALL — I5 never fired on a posted write with a "
        f"permanently-lost B (osr_max={trace['osr_max']}). That is an unbounded "
        f"hang, which is worse than an illegal error.")
    assert trace["pulses"], (
        "sub_err1_r fired but NO HRESP=1 ever reached the ahb_sub port")
    illegal = [p for p in trace["pulses"] if not p["outstanding"]]
    assert not illegal, (
        f"AHB-ILLEGAL ERROR: {len(illegal)}/{len(trace['pulses'])} HRESP=1 pulses "
        f"were driven with NO transfer in its data phase ({illegal}). An upstream "
        f"AHB->AXI bridge may legitimately discard these, so the PS never sees a "
        f"bus error and hangs — the on-silicon symptom.")


@cocotb.test()
async def test_i5_traffic_behind_a_stuck_write_is_bounded(dut):
    """GAP-2b — traffic issued BEHIND a stuck posted write must be bounded.

    ORIGINAL HYPOTHESIS (2026-08-02), now REFUTED — kept because the negative
    result is the useful part. `sub_axi_progress = sub_r_done | sub_b_done`
    resets the ONE shared `sub_osr_ctr_r` for ALL outstanding transactions, so
    in principle any completing beat on EITHER channel re-arms the age timer of
    a transaction that is genuinely stuck — the same defect class Fix H fixed
    one level down. The route to it looked open: a posted (bufferable) write
    releases the AHB master, which is then free to issue reads that complete
    normally while the write's B is permanently lost.

    MEASURED: the route is CLOSED. XHB500 serialises the sub port — with a
    posted write's B outstanding the bridge does not complete a following read,
    so no concurrent progress can be generated and the masking condition cannot
    be created from this port. (First run, 6000-cycle read timeout: read WEDGE,
    err1_fires=0. Second run, 12000-cycle timeout — longer than the 2^13 I5
    window: read returns HRESP=ERROR, err1_fires=1, osr_max=8192, and the pulse
    is `outstanding: True`, i.e. a LEGAL error, because the read master IS
    held.) So `sub_osr_ctr_r` being shared is a latent smell, not a reachable
    defect on the ahb_sub port.

    WHAT THIS NOW ASSERTS (a real property, and the useful regression): a
    transaction issued behind a stuck posted write is terminated by a bounded,
    AHB-LEGAL error rather than hanging. If a future change lets the sub port
    pipeline across channels, the shared-counter hazard reopens and the
    `outstanding` check here is what will catch it."""
    tb, master = await _bringup(dut)
    await master.write(APER_BASE + OFF_RD, D_RD)
    await ClockCycles(dut.hclk, 2000)

    trace = {}
    w = cocotb.start_soon(_err_watch(dut, master, trace, 120000))

    await _arm_injector_persistent(tb, "s", NODES["B"]["data_id"], BYTE_PKTNUM)
    try:
        await master.write_bufferable(APER_BASE + OFF_POST, D_POST,
                                      dut.u_master, timeout=20000)
    except (TimeoutError, RuntimeError) as e:
        dut._log.info(f"[gaps] posted write: {e}")

    # Keep the OTHER channel progressing. Each completed read pulses
    # sub_r_done -> sub_axi_progress -> sub_osr_ctr_r <= 0.
    reads_ok, blocked = 0, None
    for i in range(24):
        try:
            # Timeout must exceed the I5 window (2^13 in the gaps build) or a
            # read that is merely SLOW is misread as blocked.
            got = await master.read(APER_BASE + OFF_RD, timeout=12000)
            if got == D_RD: reads_ok += 1
        except RuntimeError as e:
            blocked = "ERROR"; dut._log.info(f"[gaps] read {i} bounded: {e}"); break
        except TimeoutError as e:
            blocked = "HANG";  dut._log.info(f"[gaps] read {i} hung: {e}"); break
        await ClockCycles(dut.hclk, 200)
    w.kill()
    _release_all(tb)
    dut._log.info(f"[gaps] reads_ok={reads_ok} blocked={blocked} "
                  f"err1_fires={trace['err1_fires']} osr_max={trace['osr_max']} "
                  f"HRESP pulses={trace['pulses']}")

    # Either XHB500 serialises (the measured behaviour: the following read is
    # bounded by a legal ERROR) or it pipelines (reads complete -> the shared
    # counter is being reset -> the stuck write MUST still be timed out).
    if blocked == "ERROR":
        assert trace["err1_fires"] > 0, "read errored but no backstop fired"
        illegal = [p for p in trace["pulses"] if not p["outstanding"]]
        assert not illegal, (
            f"the bounding ERROR was AHB-illegal (no transfer in its data "
            f"phase): {illegal} — see F-1 / test_i5_error_is_ahb_legal")
    else:
        assert blocked != "HANG", (
            "UNBOUNDED: a read issued behind a stuck posted write hung with no "
            "backstop — neither serialised nor timed out.")
        assert trace["err1_fires"] > 0, (
            f"PROGRESS MASKING: {reads_ok} reads completed while a posted "
            f"write's B was permanently lost, and the backstop NEVER fired. The "
            f"single shared age counter (sub_axi_progress = sub_r_done | "
            f"sub_b_done) is reset by unrelated traffic, so a stuck transaction "
            f"is never timed out and the PS hangs unbounded.")


@cocotb.test()
async def test_i5_backstop_restores_the_path(dut):
    """GAP-2c — after the backstop fires, the window path must WORK again.

    Firing an AHB ERROR upstream abandons the transfer at the tidelink wrapper,
    but does nothing to XHB500's own FSM or to the FC node. The silicon ILA
    shows `xhb_sub_hrdyout_raw` still 0 and `sub_ext_stalled` re-arming
    immediately after the ERROR (samples 258+), i.e. the bridge is still
    wedged. If a subsequent CLEAN transaction cannot complete, the backstop is
    an error REPORT, not a recovery — and every later PS access costs another
    full timeout (~2.6 ms at 25 MHz), which presents to a host as a hang."""
    tb, master = await _bringup(dut)

    await _arm_injector_persistent(tb, "s", NODES["B"]["data_id"], BYTE_PKTNUM)
    fired = False
    try:
        await master.write(APER_BASE + OFF_INJECT, D_INJECT, timeout=60000)
    except RuntimeError:  fired = True          # HRESP=ERROR — backstop tripped
    except TimeoutError:  pass
    assert fired, "backstop never fired — cannot test post-backstop recovery"

    # Remove the fault entirely, give the link time to settle, then retry clean.
    _disarm_injector(tb, "s")
    await ClockCycles(dut.hclk, 20000)

    try:
        await master.write(APER_BASE + OFF_POST, D_POST, timeout=60000)
        await ClockCycles(dut.hclk, 2000)
        landed = _slave_bram_peek(dut, OFF_POST)
    except (TimeoutError, RuntimeError) as e:
        _release_all(tb)
        raise AssertionError(
            f"PATH DEAD AFTER BACKSTOP: with the fault REMOVED, the next clean "
            f"write still failed ({e}). The backstop reports an error but never "
            f"restores XHB500/the FC node, so the window is permanently dead "
            f"after one lost response.")
    _release_all(tb)
    assert landed == D_POST, (
        f"post-backstop write completed but landed 0x{landed:08x} != 0x{D_POST:08x}")


@cocotb.test()
async def test_i5_clean_drop_leaves_path_usable(dut):
    """GAP-2c (silicon-faithful variant) — the CAPTURED silicon wedge, in sim.

    `test_i5_backstop_restores_the_path` uses a REMOVABLE fault: once the
    injector is disarmed the pending NACK/replay converges, XHB500 finally gets
    its B, and the bridge unblocks. The on-silicon capture is a different and
    strictly harder case: a byte-0 (`data_id`) corruption is a CLEAN SILENT
    DROP — no CRC check (the comparison is gated on data_id), no NACK, no
    replay. The response is gone forever, so XHB500 waits for a beat that can
    never arrive, and disarming the injector changes nothing.

    Silicon ground truth (docs/ila_capA_i5_fires_2026_08_02.csv, byte 0,
    --stream 0): for ALL 3839 samples after the backstop ERROR,
    `dbg_xhb_hrdyout_raw` is 0 — never once high — `dbg_i5_ext_stalled` is 1,
    and `dbg_i5_stall_ctr` is ramping again toward the next 2^16 expiry. The
    wrapper's ERROR abandoned the transfer upstream but did NOT unwedge the
    bridge, so the window path is permanently dead and every later PS access
    costs another full timeout.

    This test asserts the property that ground truth denies: after a
    silently-dropped response is backstopped, a subsequent CLEAN access still
    works."""
    tb, master = await _bringup(dut)

    await _arm_injector(tb, "s", NODES["B"]["data_id"], BYTE_DATA_ID)
    fired, cls = False, None
    try:
        await master.write(APER_BASE + OFF_INJECT, D_INJECT, timeout=60000)
        cls = "RECOVER"
    except RuntimeError: cls = "ERROR"; fired = True
    except TimeoutError: cls = "WEDGE"
    dut._log.info(f"[gaps] clean-drop write: {cls}")
    _disarm_injector(tb, "s")
    await ClockCycles(dut.hclk, 20000)

    assert cls != "RECOVER", (
        "byte-0 (data_id) corruption RECOVERED — unexpected: it should be an "
        "undetectable silent drop. Re-check the injector byte mapping.")
    assert fired, f"silently-dropped B was not backstopped at all (class={cls})"

    try:
        await master.write(APER_BASE + OFF_POST, D_POST, timeout=60000)
        await ClockCycles(dut.hclk, 2000)
        landed = _slave_bram_peek(dut, OFF_POST)
    except (TimeoutError, RuntimeError) as e:
        _release_all(tb)
        raise AssertionError(
            f"PATH DEAD AFTER A SILENTLY-DROPPED RESPONSE: the next CLEAN write "
            f"failed ({e}) even though the fault is gone. Matches the silicon "
            f"ILA (xhb_hrdyout_raw never returns high). The backstop reports an "
            f"error but cannot restore XHB500 — one lost response kills the "
            f"window path permanently.")
    _release_all(tb)
    assert landed == D_POST, (
        f"post-drop write completed but landed 0x{landed:08x} != 0x{D_POST:08x}")


@cocotb.test()
async def test_i5_rearms_after_abort(dut):
    """GAP-2d — a SECOND lost response after an abort must also be timed out.

    On expiry the RTL zeroes `sub_wr_os_ctr`/`sub_rd_os_r` to abandon the
    timed-out transaction (tidelink_top.sv ~:1651-1652). The abandoned response
    may still arrive afterwards; with the tracker already at zero it is either
    ignored or, worse, decrements the accounting of a LATER transaction — after
    which a second genuinely-lost response is never timed out and the PS hangs
    with no backstop at all."""
    tb, master = await _bringup(dut)

    async def trip(tag):
        await _arm_injector_persistent(tb, "s", NODES["B"]["data_id"], BYTE_PKTNUM)
        got = None
        try:
            await master.write(APER_BASE + OFF_INJECT, D_INJECT, timeout=60000)
            got = "RECOVER"
        except RuntimeError: got = "ERROR"
        except TimeoutError: got = "WEDGE"
        dut._log.info(f"[gaps] trip {tag}: {got}")
        _disarm_injector(tb, "s")
        await ClockCycles(dut.hclk, 20000)
        return got

    first  = await trip("1st")
    assert first == "ERROR", f"1st lost response was not backstopped ({first})"
    second = await trip("2nd")
    _release_all(tb)
    assert second == "ERROR", (
        f"BACKSTOP DID NOT RE-ARM: the 2nd permanently-lost response gave "
        f"'{second}', not a bounded HRESP=ERROR. After one abort the outstanding "
        f"tracker no longer bounds a stuck transaction.")
